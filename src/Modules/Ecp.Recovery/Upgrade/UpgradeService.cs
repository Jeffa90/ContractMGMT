namespace Ecp.Recovery;

public static class UpgradePhrases
{
    /// <summary>The words an operator types to confirm an upgrade. They name both versions, so an upgrade cannot be confirmed by habit.</summary>
    public static string For(string from, string to) => $"UPGRADE {from} TO {to}";
}

public static class UpgradeLeases
{
    /// <summary>Names the upgrade in progress. An upgrade also holds <see cref="RecoveryLeases.Exclusive"/>, so no backup, restore or validation starts beside it.</summary>
    public const string Exclusive = "upgrade.exclusive";
}

public sealed record PlannedMigration(string Module, string Id, IReadOnlyList<string> Categories, IReadOnlyList<string> Objects, bool ReviewRequired, bool Reviewed);

public sealed record UpgradePlan(PreflightReport Preflight, UpgradeManifest? Manifest, IReadOnlyList<PlannedMigration> Migrations, string FromVersion, string ToVersion, string ConfirmationPhrase);

public sealed record UpgradeRequest(string BackupId, string Reason, string ConfirmationText, OperatorIdentity Operator, IReadOnlyList<string> AcceptedWarningCodes, string? ExpectedManifestSha256 = null, int QuiescenceSeconds = 60);

public sealed record ModuleStep(string Module, string From, string To, int Migrations, long Milliseconds, string Outcome, string? Failure);

public sealed record QuiescenceResult(bool Clear, int LeasesAtStart, long WaitedMilliseconds, string Note);

public sealed record UpgradeResult(Guid RunId, string Kind, string Outcome, string? Failure, string FromVersion, string ToVersion, string? ManifestSha256, string BackupId, PreflightReport? Preflight, QuiescenceResult? Quiescence,
    IReadOnlyList<ModuleStep> Steps, ValidationReport? Validation, bool MaintenanceReleased, string? EvidenceFile, string Subject, DateTime StartedUtc, DateTime CompletedUtc, string CorrelationId)
{
    public bool Succeeded => Outcome is "Succeeded" or "SucceededWithWarnings";
}

public interface IUpgradeService
{
    /// <summary>What an upgrade of the running installation would do, with the pre-flight findings. Changes nothing.</summary>
    Task<UpgradePlan> PlanAsync(string? backupId, CancellationToken ct = default);

    /// <summary>Upgrades the running installation: verified backup, maintenance mode, exclusive lease, quiescence, migrations in order, validation, then release. A failure keeps maintenance mode on.</summary>
    Task<UpgradeResult> ApplyAsync(UpgradeRequest request, CancellationToken ct = default);

    /// <summary>The SQL the pending migrations of a module would run, as generated by the migration engine from the compiled migrations. For human review; never executed from here.</summary>
    Task<string> ScriptAsync(string module, CancellationToken ct = default);

    /// <summary>Every migration of every module: applied or pending, what kind of change it is, whether it needed and has a review, and whether the database agrees with its recorded checksum. Read-only.</summary>
    Task<MigrationReport> MigrationReportAsync(CancellationToken ct = default);
}

/// <summary>Whether a database already holds an installation (any module has an applied migration). Used to keep a bare <c>migrate</c> from touching an installation in Production.</summary>
public static class UpgradeInstallation
{
    public static async Task<bool> HasInstallationAsync(IServiceProvider services, CancellationToken ct = default)
        => (await UpgradeScopes.AppliedAsync(services, ct)).Values.Any(v => v.Count > 0);
}

internal sealed class UpgradeService(
    IServiceProvider root, UpgradeCatalogue catalogue, IUpgradePreflight preflight, IInstallationValidator validator, IInstallationInventory inventory, IDatabaseBackupProvider database,
    IOptions<RecoveryOptions> recovery, DatabaseOptions databaseOptions, EvidenceWriter evidence, IClock clock, ILogger<UpgradeService> log) : IUpgradeService
{
    private RecoveryOptions Options => recovery.Value;

    private UpgradeTarget Active() => new(root, databaseOptions.ConnectionString, database.Supported ? database.ActiveDatabaseName : "", true, "running installation");

    public async Task<UpgradePlan> PlanAsync(string? backupId, CancellationToken ct = default)
    {
        var report = await preflight.RunAsync(Active(), new PreflightOptions(backupId, PreflightPhase.Advisory), ct);
        var manifest = catalogue.ManifestTo(UpgradeVersions.Current);
        var planned = manifest is null ? [] : manifest.NewMigrations.Where(n => report.PendingMigrations.Contains(n.Module + "/" + n.Id)).Select(n => new PlannedMigration(n.Module, n.Id, n.Categories, n.Objects, n.ReviewRequired, n.Reviewed)).ToList();
        var from = report.State == UpgradeStateKind.AtSource ? report.SourceVersion : manifest?.SourcePlatformVersion ?? "?";
        return new UpgradePlan(report, manifest, planned, from, UpgradeVersions.Current, UpgradePhrases.For(from, UpgradeVersions.Current));
    }

    public Task<UpgradeResult> ApplyAsync(UpgradeRequest request, CancellationToken ct = default) => ExecuteAsync(Active(), request, OperationKinds.Upgrade, confirmationChecked: false, ct);

    public async Task<MigrationReport> MigrationReportAsync(CancellationToken ct = default)
    {
        var compiled = UpgradePreflight.Compiled(root.GetServices<ModuleDescriptor>());
        var manifest = catalogue.ManifestTo(UpgradeVersions.Current);
        var applied = await UpgradeScopes.AppliedAsync(root, ct);
        var state = UpgradeStateDetector.Detect(applied, compiled, catalogue, manifest?.SupportedSourceVersions ?? []);
        await using var scope0 = root.CreateAsyncScope();
        var recorded = await scope0.ServiceProvider.GetRequiredService<IMigrationRecords>().ListAsync(ct);
        var freshIds = manifest?.NewMigrations.ToDictionary(n => n.Module + "/" + n.Id, StringComparer.Ordinal) ?? [];
        var modules = new List<MigrationReportModule>();
        foreach (var m in compiled.Modules)
        {
            var have = applied.TryGetValue(m.Module, out var list) ? list : [];
            var rows = m.Migrations.Select(e =>
            {
                freshIds.TryGetValue(m.Module + "/" + e.Id, out var fresh);
                var needs = e.Categories.Any(MigrationCategories.NeedReview.Contains);
                var reviewed = !needs || catalogue.Reviews.Entries.Any(r => r.Module == m.Module && r.Migration == e.Id) || fresh?.Reviewed == true;
                var rec = recorded?.FirstOrDefault(r => r.Module == m.Module && r.MigrationId == e.Id);
                var recState = recorded is null ? "not recorded yet" : rec is null ? "not recorded" : rec.Checksum == e.Checksum ? "matches" : "DIFFERS";
                return new MigrationReportRow(e.Id, have.Contains(e.Id) ? "Applied" : "Pending", e.Categories, e.Objects, needs, reviewed, have.Contains(e.Id) ? recState : null);
            }).ToList();
            modules.Add(new MigrationReportModule(m.Module, m.SchemaVersion, rows.Count(r => r.Status == "Applied"), rows.Count(r => r.Status == "Pending"), rows));
        }
        IReadOnlyList<DriftItem>? drift = null;
        try
        {
            await using var scope = root.CreateAsyncScope();
            using var _ = scope.ServiceProvider.GetRequiredService<TenantContext>().UseInstallationScope();
            drift = await SchemaDrift.CheckAsync(scope.ServiceProvider, applied, ct);
        }
        catch (Exception ex) when (ex is Microsoft.Data.SqlClient.SqlException or InvalidOperationException) { drift = null; }
        var problems = manifest is null ? [] : UpgradeManifestValidator.Validate(manifest, catalogue, compiled);
        return new MigrationReport(UpgradeVersions.Current, state.SourceVersion ?? (state.Kind == UpgradeStateKind.AtTarget ? UpgradeVersions.Current : "unknown"), state.Kind, manifest?.ManifestSha256, problems, modules, drift,
            manifest?.BreakingChanges ?? [], manifest?.OperationalActions ?? [], manifest?.CompatibilityWarnings ?? [], manifest?.Rollback);
    }

    public async Task<string> ScriptAsync(string module, CancellationToken ct = default)
    {
        await using var scope = root.CreateAsyncScope();
        using var _ = scope.ServiceProvider.GetRequiredService<TenantContext>().UseInstallationScope();
        var descriptor = scope.ServiceProvider.GetServices<ModuleDescriptor>().FirstOrDefault(m => string.Equals(m.Name, module, StringComparison.Ordinal)) ?? throw new DomainException("unknown_module", "That module does not exist.");
        var context = (DbContext)scope.ServiceProvider.GetRequiredService(descriptor.DbContextType);
        if (!context.Database.IsSqlServer()) throw new DomainException("script_unsupported", "Migration scripts are generated for SQL Server only.");
        var applied = (await context.Database.GetAppliedMigrationsAsync(ct)).OrderBy(x => x, StringComparer.Ordinal).LastOrDefault();
        var script = context.GetService<IMigrator>().GenerateScript(fromMigration: applied, toMigration: null, MigrationsSqlGenerationOptions.NoTransactions);
        return $"-- Pending migrations of module {module}, generated from the compiled migrations for review.\n-- Applied up to: {applied ?? "(nothing)"}\n-- This script is for reading. The platform applies migrations itself, under maintenance mode, after a verified backup.\n{script}";
    }

    /// <summary>The procedure itself, against any installation: the running one, or a restored copy for a rehearsal (whose own confirmation the rehearsal service has already checked).</summary>
    internal async Task<UpgradeResult> ExecuteAsync(UpgradeTarget target, UpgradeRequest request, string kind, bool confirmationChecked, CancellationToken ct = default)
    {
        var started = clock.UtcNow;
        var correlation = Guid.NewGuid().ToString("N");
        if (string.IsNullOrWhiteSpace(request.Reason)) throw new DomainException("reason_required", "A reason is required to upgrade.");
        request = request with { Reason = Redaction.Clean(request.Reason.Trim()) };
        var manifest = catalogue.ManifestTo(UpgradeVersions.Current) ?? throw new DomainException("upgrade_unknown_target", $"This build (platform {UpgradeVersions.Current}) has no upgrade manifest, so no upgrade to it is supported.");
        if (request.ExpectedManifestSha256 is { Length: > 0 } expected && !string.Equals(expected, manifest.ManifestSha256, StringComparison.OrdinalIgnoreCase))
            throw new DomainException("manifest_unexpected", "The upgrade manifest is not the one you expected (its SHA-256 differs). Do not upgrade with a manifest you cannot account for.");

        // The words to type name the version the installation really is at, which the operator has read in the pre-flight report.
        var compiled = UpgradePreflight.Compiled(target.Services.GetServices<ModuleDescriptor>());
        var applied = await UpgradeScopes.AppliedAsync(target.Services, ct);
        var state = UpgradeStateDetector.Detect(applied, compiled, catalogue, manifest.SupportedSourceVersions);
        var from = state.SourceVersion ?? manifest.SourcePlatformVersion;
        var phrase = UpgradePhrases.For(from, manifest.TargetPlatformVersion);
        if (!confirmationChecked && !string.Equals(request.ConfirmationText?.Trim(), phrase, StringComparison.Ordinal)) throw new DomainException("confirmation_required", $"Type exactly “{phrase}” to confirm the upgrade.");
        if (state.Kind == UpgradeStateKind.AtTarget) throw new DomainException("upgrade_not_needed", "Every migration this version knows is already applied. There is nothing to upgrade.");

        // 1. Pre-flight in its strict phase: blockers refuse; warnings need the owner's explicit acceptance, by code.
        var report = await preflight.RunAsync(target, new PreflightOptions(request.BackupId, PreflightPhase.Apply), ct);
        if (report.Outcome == PreflightOutcome.Blocked || report.State != UpgradeStateKind.AtSource)
            throw new DomainException("upgrade_blocked", "The upgrade cannot start: " + string.Join(" ", report.Blockers.Select(b => $"{b.Code} {b.Title}.").Take(6)) + (report.Blockers.Any() ? "" : $"The installation is {report.State}."));
        var unaccepted = report.Checks.Where(c => c.Outcome is CheckOutcome.Warning or CheckOutcome.NotVerified && !request.AcceptedWarningCodes.Contains(c.Code, StringComparer.OrdinalIgnoreCase)).ToList();
        if (unaccepted.Count > 0)
            throw new DomainException("warnings_not_accepted", "The upgrade needs the owner's explicit acceptance of: " + string.Join(", ", unaccepted.Select(c => $"{c.Code} ({c.Title})")) + ".");

        // 2. Exclusive leases: nothing else may back up, restore, validate or upgrade this installation meanwhile.
        var scopes = target.Services.GetRequiredService<IServiceScopeFactory>();
        var owner = $"{Environment.MachineName}:{Environment.ProcessId}:{Guid.NewGuid():N}";
        var ttl = TimeSpan.FromMinutes(Math.Max(2, Options.LeaseMinutes));
        await using var recoveryLease = await LeaseHolder.TryAcquireAsync(scopes, RecoveryLeases.Exclusive, IOperationLeases.InstallationScope, owner, $"upgrade {from} to {manifest.TargetPlatformVersion}", ttl, ct)
            ?? throw new DomainException("operation_in_progress", await RecoveryLeases.DescribeBusyAsync(scopes, ct));
        await using var upgradeLease = await LeaseHolder.TryAcquireAsync(scopes, UpgradeLeases.Exclusive, IOperationLeases.InstallationScope, owner, $"upgrade {from} to {manifest.TargetPlatformVersion}", ttl, ct)
            ?? throw new DomainException("upgrade_in_progress", "Another upgrade holds the upgrade lease. Only one upgrade runs at a time.");

        // Re-check under the lease: the state must still be the one the pre-flight judged, and maintenance mode must still be on.
        var appliedNow = await UpgradeScopes.AppliedAsync(target.Services, ct);
        if (UpgradeStateDetector.Detect(appliedNow, compiled, catalogue, manifest.SupportedSourceVersions).Kind != UpgradeStateKind.AtSource)
            throw new DomainException("upgrade_state_changed", "The installation's migrations changed while the upgrade was starting. Run the pre-flight again.");

        var run = await InScope(target, request.Operator, correlation, s => s.GetRequiredService<IOperationHistory>().StartAsync(kind, $"{from} to {manifest.TargetPlatformVersion}", request.Reason, request.Operator, ct));
        await RecordAuditAsync(target, request.Operator, correlation, kind == OperationKinds.Upgrade ? "operations.upgrade.started" : "operations.upgrade.rehearsal.started", from, manifest, request, null, ct);

        QuiescenceResult? quiescence = null; var steps = new List<ModuleStep>(); ValidationReport? validation = null; string? failure = null; var released = false;
        var maintenanceBefore = await InScope(target, request.Operator, correlation, s => s.GetRequiredService<IMaintenanceService>().GetAsync(ct));
        try
        {
            // 3. Quiescence: nothing new starts (maintenance mode); wait for what is running to finish.
            await InScope(target, request.Operator, correlation, s => s.GetRequiredService<IMaintenanceService>().EnableAsync($"Upgrade {from} to {manifest.TargetPlatformVersion} in progress", request.Operator, MaintenanceCauses.UpgradeInProgress, ct));
            quiescence = await WaitForQuiescenceAsync(target, request.Operator, correlation, TimeSpan.FromSeconds(Math.Max(0, request.QuiescenceSeconds)), ct);
            if (!quiescence.Clear) throw new DomainException("not_quiescent", "Background work did not finish in time, so no migration was started. " + quiescence.Note);

            // 4. What the data looks like immediately before the first migration: the post-upgrade comparison is against this.
            var before = await inventory.CollectAsync(target.Services, Options.TableChecksums, ct);
            IReadOnlyList<string> policiesBefore;
            await using (var scope = target.Services.CreateAsyncScope())
            {
                using var _ = scope.ServiceProvider.GetRequiredService<TenantContext>().UseInstallationScope();
                policiesBefore = await SchemaInspector.PoliciesAsync(scope.ServiceProvider, ct);
            }
            recoveryLease.ThrowIfLost(); upgradeLease.ThrowIfLost();

            // 5. Migrate, one module at a time in tier order. The first failure stops everything.
            var runner = target.Services.GetRequiredService<MigrationRunner>();
            foreach (var module in runner.OrderedModules)
            {
                var latest = compiled.Find(module.Name)?.SchemaVersion ?? "";
                var had = appliedNow.TryGetValue(module.Name, out var ids) ? ids : [];
                var count = compiled.Find(module.Name)?.Migrations.Count(m => !had.Contains(m.Id)) ?? 0;
                if (count == 0) continue;
                var watch = Stopwatch.StartNew();
                try
                {
                    await runner.MigrateModuleAsync(module.Name, null, ct);
                    steps.Add(new(module.Name, had.OrderBy(x => x, StringComparer.Ordinal).LastOrDefault() ?? "(none)", latest, count, watch.ElapsedMilliseconds, "Applied", null));
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    steps.Add(new(module.Name, had.OrderBy(x => x, StringComparer.Ordinal).LastOrDefault() ?? "(none)", latest, count, watch.ElapsedMilliseconds, "Failed", Redaction.Clean(ex.GetType().Name + ": " + ex.Message)));
                    throw new DomainException("migration_failed", $"Module {module.Name} failed to migrate ({ex.GetType().Name}). Later modules were not touched.");
                }
                recoveryLease.ThrowIfLost();
            }

            // 6. Record what was verified and applied, then validate.
            await RecordMigrationsAsync(target, request.Operator, correlation, compiled, appliedNow, from, run, ct);
            validation = await ValidateAsync(target, manifest, before, policiesBefore, run, ct);
            if (validation.AllowsRelease)
            {
                await InScope(target, request.Operator, correlation, s => s.GetRequiredService<IMaintenanceService>().DisableAsync($"Upgrade {from} to {manifest.TargetPlatformVersion} validated ({validation.Outcome})", request.Operator, acknowledgeRestoreState: true, ct));
                released = true;
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            failure = Redaction.Clean(ex is DomainException or IOException ? ex.Message : "The upgrade failed unexpectedly (" + ex.GetType().Name + "). See the application log with the correlation id.");
            log.LogError(ex, "Upgrade from {From} to {To} failed in {Target}.", from, manifest.TargetPlatformVersion, target.Label);
        }

        var outcome = failure is not null ? "Failed" : validation is { Outcome: ValidationOutcome.Passed } ? "Succeeded" : validation is { AllowsRelease: true } ? "SucceededWithWarnings" : "Failed";
        if (outcome == "Failed" && failure is null) failure = $"Post-upgrade validation did not pass ({validation?.Outcome}). The installation is held in maintenance mode.";
        var completed = clock.UtcNow;
        var result = new UpgradeResult(run, kind, outcome, failure, from, manifest.TargetPlatformVersion, manifest.ManifestSha256, request.BackupId, report, quiescence, steps, validation, released && outcome != "Failed", null, target.Label, started, completed, correlation);
        var file = await evidence.WriteUpgradeAsync(result, request, report, ct);
        result = result with { EvidenceFile = file };

        // 7. Bookkeeping. On failure the installation stays in maintenance mode, in an explicit failed state, until an operator acts.
        try
        {
            if (outcome == "Failed")
                await InScope(target, request.Operator, CorrelationOr(correlation), s => s.GetRequiredService<IMaintenanceService>().EnableAsync($"Upgrade {from} to {manifest.TargetPlatformVersion} failed: {Short(failure)} Roll back by restoring the verified pre-upgrade backup.", request.Operator, MaintenanceCauses.UpgradeFailed, CancellationToken.None));
            var status = outcome == "Failed" ? OperationStatuses.Failed : outcome == "Succeeded" ? OperationStatuses.Completed : OperationStatuses.CompletedWithWarnings;
            var summary = outcome == "Failed" ? $"Upgrade failed: {Short(failure)}" : $"Upgrade {from} to {manifest.TargetPlatformVersion} validated ({validation?.Outcome}).";
            var detail = JsonSerializer.Serialize(new { from, to = manifest.TargetPlatformVersion, manifestSha256 = manifest.ManifestSha256, backupId = request.BackupId, steps = steps.Select(s => new { s.Module, s.Migrations, s.Outcome, s.Milliseconds }), validation = validation?.Outcome.ToString(), validationChecks = validation?.Checks.Select(c => new { c.Code, c.Title, outcome = c.Outcome.ToString(), severity = c.Severity.ToString(), c.Description, detail = Redaction.Clean(c.TechnicalDetail), c.Remediation }), evidence = file });
            await InScope(target, request.Operator, correlation, s => s.GetRequiredService<IOperationHistory>().FinishAsync(run, status, summary, detail, CancellationToken.None));
            await RecordAuditAsync(target, request.Operator, correlation, outcome == "Failed" ? "operations.upgrade.failed" : (kind == OperationKinds.Upgrade ? "operations.upgrade.completed" : "operations.upgrade.rehearsal.completed"), from, manifest, request, detail, CancellationToken.None);
        }
        catch (Exception ex) when (ex is DomainException or InvalidOperationException or DbUpdateException or Microsoft.Data.SqlClient.SqlException)
        {
            log.LogError(ex, "Upgrade bookkeeping failed after the upgrade finished.");
        }
        _ = maintenanceBefore;
        return result;
    }

    private static string CorrelationOr(string c) => c;
    private static string Short(string? s) => s is null ? "" : s.Length <= 200 ? s : s[..200] + "…";

    private static async Task<T> InScope<T>(UpgradeTarget target, OperatorIdentity op, string correlation, Func<IServiceProvider, Task<T>> body)
    {
        await using var scope = target.Services.CreateAsyncScope();
        var actor = scope.ServiceProvider.GetRequiredService<ActorContext>();
        actor.Type = ActorType.System; actor.Source = "Upgrade"; actor.ActorId = op.Id; actor.CorrelationId = correlation;
        return await body(scope.ServiceProvider);
    }

    private static Task InScope(UpgradeTarget target, OperatorIdentity op, string correlation, Func<IServiceProvider, Task> body)
        => InScope<int>(target, op, correlation, async s => { await body(s); return 0; });

    private async Task RecordAuditAsync(UpgradeTarget target, OperatorIdentity op, string correlation, string action, string from, UpgradeManifest manifest, UpgradeRequest request, string? detailJson, CancellationToken ct)
    {
        var payload = detailJson ?? JsonSerializer.Serialize(new { from, to = manifest.TargetPlatformVersion, manifestSha256 = manifest.ManifestSha256, backupId = request.BackupId, accepted = request.AcceptedWarningCodes, @operator = op.Id });
        await InScope(target, op, correlation, s => s.GetRequiredService<OperationAudit>().RecordAsync(new AuditEntry(action, "Upgrade", $"{from}->{manifest.TargetPlatformVersion}", action.EndsWith("failed", StringComparison.Ordinal) ? AuditOutcome.Failed : AuditOutcome.Success,
            Reason: request.Reason, NewValuesJson: payload), ct));
    }

    private async Task<QuiescenceResult> WaitForQuiescenceAsync(UpgradeTarget target, OperatorIdentity op, string correlation, TimeSpan timeout, CancellationToken ct)
    {
        var watch = Stopwatch.StartNew();
        int Count(IReadOnlyList<LeaseInfo> l) => l.Count(x => x.IsActive && x.Name == "background.jobs");
        var first = await InScope(target, op, correlation, async s => Count(await s.GetRequiredService<IOperationLeases>().ListAsync(ct)));
        var now = first;
        while (now > 0 && watch.Elapsed < timeout)
        {
            await Task.Delay(TimeSpan.FromMilliseconds(500), ct);
            now = await InScope(target, op, correlation, async s => Count(await s.GetRequiredService<IOperationLeases>().ListAsync(ct)));
        }
        return new QuiescenceResult(now == 0, first, watch.ElapsedMilliseconds, now == 0 ? (first == 0 ? "No background work was running." : "Running background work finished.") : $"{now} job lease(s) were still held after {timeout.TotalSeconds:0} seconds.");
    }

    private async Task RecordMigrationsAsync(UpgradeTarget target, OperatorIdentity op, string correlation, MigrationLedger compiled, IReadOnlyDictionary<string, IReadOnlyList<string>> appliedBefore, string from, Guid run, CancellationToken ct)
    {
        var records = new List<NewMigrationRecord>();
        foreach (var (module, entry) in compiled.All)
        {
            var wasApplied = appliedBefore.TryGetValue(module, out var ids) && ids.Contains(entry.Id);
            records.Add(new NewMigrationRecord(module, entry.Id, entry.Checksum, compiled.Generator, wasApplied ? from : UpgradeVersions.Current, wasApplied ? "adopted" : "applied", wasApplied ? null : run));
        }
        await InScope(target, op, correlation, s => s.GetRequiredService<IMigrationRecords>().AddAsync(records, ct));
    }

    /// <summary>The post-upgrade validation: the ordinary checks in their post-upgrade profile, plus the upgrade's own (UPV) checks.</summary>
    private async Task<ValidationReport> ValidateAsync(UpgradeTarget target, UpgradeManifest manifest, InventorySnapshot before, IReadOnlyList<string> policiesBefore, Guid run, CancellationToken ct)
    {
        var started = clock.UtcNow;
        var report = await validator.ValidateAsync(new ValidationTarget(target.Services, target.ConnectionString, target.DatabaseName, Restored: false, Manifest: null, HashDocumentContent: true, Subject: $"{target.Label} after upgrade to {manifest.TargetPlatformVersion}",
            Profile: ValidationProfile.PostUpgrade, Upgrade: new UpgradeExpectation(manifest, before, policiesBefore)), ct);
        var extra = new List<ValidationCheck>();
        ValidationCheck Make(string code, string title, CheckOutcome o, CheckSeverity sev, string d, string detail, string fix) => new(code, title, o, sev, d, Redaction.Clean(detail), fix, report.CorrelationId);
        try
        {
            var compiled = UpgradePreflight.Compiled(target.Services.GetServices<ModuleDescriptor>());
            await using var scope = target.Services.CreateAsyncScope();
            using var _ = scope.ServiceProvider.GetRequiredService<TenantContext>().UseInstallationScope();
            var records = await scope.ServiceProvider.GetRequiredService<IMigrationRecords>().ListAsync(ct);
            var missing = compiled.All.Where(c => records is null || records.All(r => r.Module != c.Module || r.MigrationId != c.Entry.Id)).Select(c => $"{c.Module}/{c.Entry.Id}").ToList();
            var wrong = records is null ? [] : records.Where(r => compiled.Find(r.Module)?.Migrations.FirstOrDefault(m => m.Id == r.MigrationId) is { } m && m.Checksum != r.Checksum).Select(r => $"{r.Module}/{r.MigrationId}").ToList();
            extra.Add(missing.Count == 0 && wrong.Count == 0
                ? Make("UPV-001", "Migration records", CheckOutcome.Passed, CheckSeverity.Info, "Every migration is recorded with the checksum the manifest declares.", $"{records?.Count} record(s)", "")
                : Make("UPV-001", "Migration records", CheckOutcome.Failed, CheckSeverity.High, "The migration records are incomplete or disagree with the manifest.", $"missing: {string.Join(", ", missing.Take(5))}; differing: {string.Join(", ", wrong.Take(5))}", "Do not release this installation. Roll back by restoring the verified pre-upgrade backup."));
            var applied = await UpgradeScopes.AppliedAsync(target.Services, ct);
            var drift = await SchemaDrift.CheckAsync(scope.ServiceProvider, applied, ct);
            extra.Add(drift is null ? Make("UPV-002", "Schema matches the final model", CheckOutcome.NotVerified, CheckSeverity.Medium, "Schema comparison is available on SQL Server only.", "", "")
                : drift.Count == 0 ? Make("UPV-002", "Schema matches the final model", CheckOutcome.Passed, CheckSeverity.Info, "The upgraded database matches the schema of the target version: no table or column is missing, extra or of another type.", "", "")
                : Make("UPV-002", "Schema matches the final model", CheckOutcome.Failed, CheckSeverity.Critical, $"The upgraded database differs from the target schema in {drift.Count} place(s).", string.Join("; ", drift.Take(10).Select(d => $"{d.Object}: {d.Problem}")), "Do not release this installation. Roll back by restoring the verified pre-upgrade backup."));
            var state = UpgradeStateDetector.Detect(applied, compiled, catalogue, manifest.SupportedSourceVersions);
            extra.Add(state.Kind == UpgradeStateKind.AtTarget
                ? Make("UPV-003", "Schema version", CheckOutcome.Passed, CheckSeverity.Info, $"Every module is at the schema version of platform {manifest.TargetPlatformVersion}.", string.Join(", ", compiled.Modules.Select(m => $"{m.Module}={m.SchemaVersion[..Math.Min(14, m.SchemaVersion.Length)]}")), "")
                : Make("UPV-003", "Schema version", CheckOutcome.Failed, CheckSeverity.Critical, "The installation is not at the target schema version.", state.Kind.ToString(), "Roll back by restoring the verified pre-upgrade backup."));
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            extra.Add(Make("UPV-000", "Upgrade-specific checks", CheckOutcome.NotVerified, CheckSeverity.High, "The upgrade-specific checks could not be completed.", ex.GetType().Name + ": " + ex.Message, "Run the validation again."));
        }
        var all = report.Checks.Concat(extra).OrderBy(c => c.Code, StringComparer.Ordinal).ToList();
        return new ValidationReport(report.Subject, started, clock.UtcNow, ValidationReport.Summarise(all), all, report.CorrelationId);
    }
