<#
.SYNOPSIS
    Stamps environment variables into a published ASP.NET Core web.config so they
    reach the app through the IIS ASP.NET Core Module.

.DESCRIPTION
    Shared by scripts/publish.ps1 (manual deploys) and .github/workflows/iis-deploy.yml
    (pipeline deploys), so both write web.config the same way. Existing entries with the
    same name are replaced rather than duplicated, so re-running against the same file
    is safe. Values are never echoed - only names are logged.

.PARAMETER WebConfigPath
    Path to the web.config generated by dotnet publish.

.PARAMETER Environment
    Value for ASPNETCORE_ENVIRONMENT (e.g. QA, Production).

.PARAMETER EnvironmentVariables
    Extra name/value pairs, e.g. secrets using IConfiguration's double-underscore
    section syntax (Snowflake__Accounts__Dev, Anthropic__ApiKey, ...).

.EXAMPLE
    ./scripts/ci/Set-WebConfigEnvironment.ps1 -WebConfigPath C:\deploy\app\web.config -Environment QA -EnvironmentVariables @{ "Anthropic__ApiKey" = $key }
#>
param(
    [Parameter(Mandatory = $true)]
    [string]$WebConfigPath,

    [Parameter(Mandatory = $true)]
    [string]$Environment,

    [hashtable]$EnvironmentVariables = @{}
)

$ErrorActionPreference = "Stop"

$WebConfigPath = (Resolve-Path $WebConfigPath).Path
[xml]$webConfig = Get-Content $WebConfigPath

# dotnet publish nests aspNetCore under <location> for in-process hosting; fall back to the
# unwrapped shape in case a hand-written web.config is in play.
$aspNetCore = $webConfig.SelectSingleNode("/configuration/location/system.webServer/aspNetCore")
if (-not $aspNetCore) {
    $aspNetCore = $webConfig.SelectSingleNode("/configuration/system.webServer/aspNetCore")
}
if (-not $aspNetCore) {
    throw "No <aspNetCore> element found in $WebConfigPath."
}

$envVarsNode = $aspNetCore.SelectSingleNode("environmentVariables")
if (-not $envVarsNode) {
    $envVarsNode = $webConfig.CreateElement("environmentVariables")
    $aspNetCore.AppendChild($envVarsNode) | Out-Null
}

function Set-EnvVar([string]$name, [string]$value) {
    # Match case-insensitively: Windows env var names and IConfiguration keys both are.
    foreach ($existing in @($envVarsNode.SelectNodes("environmentVariable"))) {
        if ($existing.GetAttribute("name") -ieq $name) {
            $envVarsNode.RemoveChild($existing) | Out-Null
        }
    }
    $node = $webConfig.CreateElement("environmentVariable")
    $node.SetAttribute("name", $name)
    $node.SetAttribute("value", $value)
    $envVarsNode.AppendChild($node) | Out-Null
    Write-Host "    $name"
}

Set-EnvVar "ASPNETCORE_ENVIRONMENT" $Environment
foreach ($key in $EnvironmentVariables.Keys) {
    Set-EnvVar $key $EnvironmentVariables[$key]
}

$webConfig.Save($WebConfigPath)
